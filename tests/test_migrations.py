"""Tests that the migrations and the models still describe the same schema.

This is the guard that makes migrations trustworthy. db.init_db() calls
create_all, so a column added to a model appears immediately in a local SQLite
file and in the test suite, and everything goes on passing -- while Supabase,
where create_all cannot alter an existing table, silently does not have it. The
mismatch would surface as a 500 in production and nowhere else.

Running `alembic check` against a freshly migrated database closes that gap: a
model change with no accompanying migration fails here.

No network. Each test migrates a throwaway SQLite file in tmp_path.
"""
import os
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect

import db as db_module

PROJECT_ROOT = Path(__file__).resolve().parent.parent


@pytest.fixture
def alembic_config(tmp_path, monkeypatch):
    """Alembic pointed at an empty database of its own.

    migrations/env.py reads db.get_database_url(), so setting DATABASE_URL is
    all it takes to redirect it -- the same mechanism the deployment uses.
    """
    database = tmp_path / "migration_test.db"
    url = f"sqlite:///{database.as_posix()}"
    monkeypatch.setenv("DATABASE_URL", url)

    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(PROJECT_ROOT / "migrations"))

    yield config, url

    # The app caches its engine per process; a test that pointed it at a
    # temporary file must not leave it there.
    db_module.reset_engine_for_testing(None)


def test_upgrade_creates_every_table_the_models_define(alembic_config):
    config, url = alembic_config
    command.upgrade(config, "head")

    engine = create_engine(url)
    try:
        tables = set(inspect(engine).get_table_names())
    finally:
        engine.dispose()

    expected = set(db_module.Base.metadata.tables)
    assert expected <= tables, f"missing: {sorted(expected - tables)}"
    assert "alembic_version" in tables


def test_the_models_and_the_migrations_agree(alembic_config):
    """The drift guard.

    If this fails, a model was changed without a migration. Generate one:

        alembic revision --autogenerate -m "what changed"

    then read it before committing -- autogenerate is a first draft, and it
    cannot see a rename (it reads as a drop plus an add, which loses the data).
    """
    config, _url = alembic_config
    command.upgrade(config, "head")

    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(
            "The models no longer match the migrations. Run "
            f'`alembic revision --autogenerate -m "..."`.\n\nDiffs: {exc}')


def test_downgrade_leaves_nothing_behind(alembic_config):
    """A migration that cannot be undone is one you cannot safely try."""
    config, url = alembic_config
    command.upgrade(config, "head")
    command.downgrade(config, "base")

    engine = create_engine(url)
    try:
        tables = set(inspect(engine).get_table_names())
    finally:
        engine.dispose()

    assert tables <= {"alembic_version"}, f"left behind: {sorted(tables)}"


def test_there_is_exactly_one_head(alembic_config):
    """Two heads mean two branches of history, and `upgrade head` becomes
    ambiguous. It happens when two people add a migration independently."""
    from alembic.script import ScriptDirectory

    config, _url = alembic_config
    heads = ScriptDirectory.from_config(config).get_heads()
    assert len(heads) == 1, f"expected one head, found {heads}"


def test_migrations_do_not_need_a_url_in_alembic_ini(alembic_config):
    """env.py takes the URL from db.get_database_url(), so the two cannot be
    pointed at different databases. A URL set in the file would win in
    surprising places, so assert the placeholder stays commented out."""
    ini = (PROJECT_ROOT / "alembic.ini").read_text(encoding="utf-8")
    live = [line for line in ini.splitlines()
            if line.strip().startswith("sqlalchemy.url")]
    assert not live, f"alembic.ini should not set a URL, found: {live}"
    assert os.environ.get("DATABASE_URL"), "the fixture should have set one"
